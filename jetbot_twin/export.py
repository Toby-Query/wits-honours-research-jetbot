"""Write the robot out for other simulators: URDF, and SDF for Gazebo.

Both are generated from hardware.py, so they carry the same mass, inertia,
geometry and friction as the twin. Neither carries the electrical model:
Gazebo's diff-drive plugin commands wheel speed directly, which is exactly
the part of the real robot (battery, bridge, motor) the twin exists to
model. Use these for geometry, sensors and environments; use the twin for
"what does command 0.3 actually do".
"""
from __future__ import annotations

from pathlib import Path


def _inertia_box(m, x, y, z):
    return (m * (y * y + z * z) / 12, m * (x * x + z * z) / 12,
            m * (x * x + y * y) / 12)


def _numbers(hw):
    r = hw.wheel_radius
    cx, cy, cz = hw.cog
    m_wheel = 0.034
    m_body = hw.mass - 2 * m_wheel
    ixx, iyy, _ = _inertia_box(m_body, hw.chassis_box[0], hw.chassis_box[1], 0.09)
    return dict(
        r=r, half_track=hw.track / 2, wheel_w=0.026, m_wheel=m_wheel,
        m_body=m_body, cog=(cx, cy, cz - r), ixx=ixx, iyy=iyy,
        izz=hw.yaw_inertia_cog,
        iw_axis=0.5 * m_wheel * r * r,
        iw_other=m_wheel * (3 * r * r + 0.026 ** 2) / 12,
        caster_r=0.00475,
        cf=(hw.caster_front_x, 0.0, 0.00475 - r),
        cr=(hw.caster_rear_x, 0.0, 0.00475 - r),
        cam=(hw.cam_pos[0], hw.cam_pos[1], hw.cam_pos[2] - r),
        mu=hw.mu_tyre, mu_c=hw.mu_caster,
        box=hw.chassis_box, box_z=0.0353 - r,
        w_max=hw.motor_w_noload * 12.0 / hw.motor_v_rated,
    )


def urdf(hw, meshes=True):
    n = _numbers(hw)
    body_vis = ('<mesh filename="meshes/body.stl"/>' if meshes else
                f'<box size="{n["box"][0]} {n["box"][1]} {n["box"][2]}"/>')
    wheel_vis = ('<mesh filename="meshes/wheel.stl"/>' if meshes else
                 f'<cylinder radius="{n["r"]}" length="{n["wheel_w"]}"/>')
    wheel_vis_rpy = "0 0 0" if meshes else "1.5708 0 0"

    def wheel(side, sign, flip):
        return f'''
  <link name="wheel_{side}">
    <inertial>
      <mass value="{n['m_wheel']:.4f}"/>
      <inertia ixx="{n['iw_other']:.3e}" iyy="{n['iw_axis']:.3e}" izz="{n['iw_other']:.3e}" ixy="0" ixz="0" iyz="0"/>
    </inertial>
    <visual><origin rpy="{'0 0 3.14159' if (flip and meshes) else wheel_vis_rpy}"/><geometry>{wheel_vis}</geometry></visual>
    <collision><origin rpy="1.5708 0 0"/><geometry><cylinder radius="{n['r']}" length="{n['wheel_w']}"/></geometry></collision>
  </link>
  <joint name="wheel_{side}_joint" type="continuous">
    <parent link="base_link"/><child link="wheel_{side}"/>
    <origin xyz="0 {sign * n['half_track']:.5f} 0"/><axis xyz="0 1 0"/>
    <limit effort="0.4" velocity="{n['w_max']:.1f}"/>
  </joint>'''

    def caster(name, p):
        return f'''
  <link name="caster_{name}">
    <inertial><mass value="0.006"/><inertia ixx="1e-7" iyy="1e-7" izz="1e-7" ixy="0" ixz="0" iyz="0"/></inertial>
    <collision><geometry><sphere radius="{n['caster_r']}"/></geometry></collision>
  </link>
  <joint name="caster_{name}_joint" type="fixed">
    <parent link="base_link"/><child link="caster_{name}"/>
    <origin xyz="{p[0]:.5f} {p[1]:.5f} {p[2]:.5f}"/>
  </joint>'''

    return f'''<?xml version="1.0"?>
<!-- Generated by jetbot_twin.export from hardware.py. Do not edit: regenerate.
     base_link is at the middle of the axle; x forward, y left, z up. -->
<robot name="jetbot">
  <link name="base_footprint"/>
  <joint name="base_joint" type="fixed">
    <parent link="base_footprint"/><child link="base_link"/>
    <origin xyz="0 0 {n['r']:.5f}"/>
  </joint>
  <link name="base_link">
    <inertial>
      <origin xyz="{n['cog'][0]:.5f} {n['cog'][1]:.5f} {n['cog'][2]:.5f}"/>
      <mass value="{n['m_body']:.4f}"/>
      <inertia ixx="{n['ixx']:.3e}" iyy="{n['iyy']:.3e}" izz="{n['izz']:.3e}" ixy="0" ixz="0" iyz="0"/>
    </inertial>
    <visual><geometry>{body_vis}</geometry></visual>
    <collision>
      <origin xyz="-0.022 0 {n['box_z']:.5f}"/>
      <geometry><box size="{n['box'][0]} {n['box'][1]} {n['box'][2]}"/></geometry>
    </collision>
  </link>{wheel('left', 1, False)}{wheel('right', -1, True)}{caster('front', n['cf'])}{caster('rear', n['cr'])}
  <link name="camera_link"/>
  <joint name="camera_joint" type="fixed">
    <parent link="base_link"/><child link="camera_link"/>
    <origin xyz="{n['cam'][0]:.5f} {n['cam'][1]:.5f} {n['cam'][2]:.5f}"/>
  </joint>
  <link name="camera_optical"/>
  <joint name="camera_optical_joint" type="fixed">
    <parent link="camera_link"/><child link="camera_optical"/>
    <origin rpy="-1.5708 0 -1.5708"/>
  </joint>
</robot>
'''


def sdf(hw, meshes=True):
    n = _numbers(hw)
    body_vis = ('<mesh><uri>meshes/body.stl</uri></mesh>' if meshes else
                f'<box><size>{n["box"][0]} {n["box"][1]} {n["box"][2]}</size></box>')

    def wheel(side, sign):
        vis = ('<mesh><uri>meshes/wheel.stl</uri></mesh>' if meshes else
               f'<cylinder><radius>{n["r"]}</radius><length>{n["wheel_w"]}</length></cylinder>')
        vpose = ("0 0 0 0 0 3.14159" if sign < 0 else "0 0 0 0 0 0") if meshes \
            else "0 0 0 1.5708 0 0"
        return f'''
    <link name="wheel_{side}">
      <pose relative_to="base_link">0 {sign * n['half_track']:.5f} 0 0 0 0</pose>
      <inertial><mass>{n['m_wheel']:.4f}</mass>
        <inertia><ixx>{n['iw_other']:.3e}</ixx><iyy>{n['iw_axis']:.3e}</iyy><izz>{n['iw_other']:.3e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <visual name="v"><pose>{vpose}</pose><geometry>{vis}</geometry>
        <material><diffuse>0.12 0.12 0.12 1</diffuse></material></visual>
      <collision name="c"><pose>0 0 0 1.5708 0 0</pose>
        <geometry><cylinder><radius>{n['r']}</radius><length>{n['wheel_w']}</length></cylinder></geometry>
        <surface><friction><ode><mu>{n['mu']}</mu><mu2>{n['mu']}</mu2></ode></friction></surface>
      </collision>
    </link>
    <joint name="wheel_{side}_joint" type="revolute">
      <parent>base_link</parent><child>wheel_{side}</child>
      <axis><xyz>0 1 0</xyz><limit><lower>-1e16</lower><upper>1e16</upper></limit></axis>
    </joint>'''

    def caster(name, p):
        return f'''
      <collision name="caster_{name}"><pose>{p[0]:.5f} {p[1]:.5f} {p[2]:.5f} 0 0 0</pose>
        <geometry><sphere><radius>{n['caster_r']}</radius></sphere></geometry>
        <surface><friction><ode><mu>{n['mu_c']}</mu><mu2>{n['mu_c']}</mu2></ode></friction></surface>
      </collision>'''

    return f'''<?xml version="1.0"?>
<!-- Generated by jetbot_twin.export from hardware.py. Do not edit: regenerate. -->
<sdf version="1.9">
  <model name="jetbot">
    <pose>0 0 {n['r']:.5f} 0 0 0</pose>
    <link name="base_link">
      <inertial>
        <pose>{n['cog'][0]:.5f} {n['cog'][1]:.5f} {n['cog'][2]:.5f} 0 0 0</pose>
        <mass>{n['m_body']:.4f}</mass>
        <inertia><ixx>{n['ixx']:.3e}</ixx><iyy>{n['iyy']:.3e}</iyy><izz>{n['izz']:.3e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <visual name="body"><geometry>{body_vis}</geometry>
        <material><diffuse>0.34 0.72 0.28 1</diffuse></material></visual>
      <collision name="box"><pose>-0.022 0 {n['box_z']:.5f} 0 0 0</pose>
        <geometry><box><size>{n['box'][0]} {n['box'][1]} {n['box'][2]}</size></box></geometry>
      </collision>{caster('front', n['cf'])}{caster('rear', n['cr'])}
      <sensor name="camera" type="wideanglecamera">
        <pose>{n['cam'][0]:.5f} {n['cam'][1]:.5f} {n['cam'][2]:.5f} 0 0 0</pose>
        <update_rate>21</update_rate>
        <camera>
          <horizontal_fov>{2.4:.3f}</horizontal_fov>
          <image><width>820</width><height>616</height></image>
          <clip><near>0.02</near><far>20</far></clip>
          <lens><type>equidistant</type><scale_to_hfov>true</scale_to_hfov>
            <cutoff_angle>1.396</cutoff_angle><env_texture_size>512</env_texture_size></lens>
        </camera>
        <topic>jetbot/camera</topic>
      </sensor>
    </link>{wheel('left', 1)}{wheel('right', -1)}
    <plugin filename="gz-sim-diff-drive-system" name="gz::sim::systems::DiffDrive">
      <left_joint>wheel_left_joint</left_joint>
      <right_joint>wheel_right_joint</right_joint>
      <wheel_separation>{2 * n['half_track']:.5f}</wheel_separation>
      <wheel_radius>{n['r']:.5f}</wheel_radius>
      <topic>jetbot/cmd_vel</topic>
      <odom_publish_frequency>50</odom_publish_frequency>
    </plugin>
  </model>
</sdf>
'''


WORLD = '''<?xml version="1.0"?>
<sdf version="1.9">
  <world name="jetbot_world">
    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose><direction>-0.5 0.1 -0.9</direction></light>
    <model name="floor"><static>true</static><link name="l">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
        <material><diffuse>0.85 0.85 0.83 1</diffuse></material></visual>
    </link></model>
    <include><uri>jetbot.sdf</uri></include>
  </world>
</sdf>
'''


def write_all(hw, out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    meshes = (out / "meshes" / "body.stl").exists()
    files = {"jetbot.urdf": urdf(hw, meshes), "jetbot.sdf": sdf(hw, meshes),
             "world.sdf": WORLD}
    written = []
    for name, text in files.items():
        (out / name).write_text(text)
        written.append(out / name)
    return written
